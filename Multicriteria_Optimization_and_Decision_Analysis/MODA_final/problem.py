def create_single_comparison_plot(results_unconstrained: Dict[str, Any],
                                  results_constrained: Dict[str, Any]):
    """
    Create single overlay comparison plot with deduplication
    """

    def deduplicate_solutions(results):
        """去重并返回唯一解"""
        prob = results['problem']
        all_solutions = results['population'].get_x()
        all_fitness = results['population'].get_f()
        pareto_f = results['pareto_front_fitness']
        pareto_x = results['pareto_front_solutions']

        # 去重所有解
        unique_solutions = {}
        for sol, fit in zip(all_solutions, all_fitness):
            permutation = prob.decode_permutation(sol)
            _, _, _, is_valid = prob.calculate_route_metrics(permutation)

            if is_valid and fit[0] < 1e5:
                route_sig = tuple(permutation)
                if route_sig not in unique_solutions or fit[0] < unique_solutions[route_sig][1][0]:
                    unique_solutions[route_sig] = (sol, fit)

        # 去重帕累托解
        unique_pareto = {}
        for sol, fit in zip(pareto_x, pareto_f):
            permutation = prob.decode_permutation(sol)
            route_sig = tuple(permutation)
            if route_sig in unique_solutions:  # 只包含有效且唯一的解
                unique_pareto[route_sig] = (sol, fit)

        unique_all_fitness = np.array([fit for sol, fit in unique_solutions.values()])
        unique_pareto_fitness = np.array([fit for sol, fit in unique_pareto.values()])

        return unique_all_fitness, unique_pareto_fitness, len(all_solutions), len(pareto_f)

    # 对两个结果都进行去重
    print("🔄 Deduplicating solutions...")

    unc_fitness, unc_pareto_f, unc_total, unc_pareto_total = deduplicate_solutions(results_unconstrained)
    con_fitness, con_pareto_f, con_total, con_pareto_total = deduplicate_solutions(results_constrained)

    print(
        f"Unconstrained: {len(unc_fitness)}/{unc_total} unique solutions, {len(unc_pareto_f)}/{unc_pareto_total} unique Pareto")
    print(
        f"Constrained: {len(con_fitness)}/{con_total} unique solutions, {len(con_pareto_f)}/{con_pareto_total} unique Pareto")

    # 检查是否有有效数据
    if len(unc_fitness) == 0 or len(con_fitness) == 0:
        print("❌ No valid unique solutions found for comparison")
        return

    # Convert to plot-friendly format (使用去重后的数据)
    unc_distances = unc_fitness[:, 0]
    unc_comfort = -unc_fitness[:, 1]
    unc_pareto_distances = unc_pareto_f[:, 0] if len(unc_pareto_f) > 0 else []
    unc_pareto_comfort = -unc_pareto_f[:, 1] if len(unc_pareto_f) > 0 else []

    con_distances = con_fitness[:, 0]
    con_comfort = -con_fitness[:, 1]
    con_pareto_distances = con_pareto_f[:, 0] if len(con_pareto_f) > 0 else []
    con_pareto_comfort = -con_pareto_f[:, 1] if len(con_pareto_f) > 0 else []

    # Create single overlay plot
    plt.figure(figsize=(12, 8))

    # Plot unconstrained data (background)
    plt.scatter(unc_distances, unc_comfort, c='lightblue', alpha=0.4, s=25,
                label=f'Unconstrained solutions ({len(unc_fitness)})')

    # Plot unconstrained Pareto front
    if len(unc_pareto_distances) > 0:
        sorted_indices = np.argsort(unc_pareto_distances)
        sorted_dist = np.array(unc_pareto_distances)[sorted_indices]
        sorted_comfort = np.array(unc_pareto_comfort)[sorted_indices]
        plt.plot(sorted_dist, sorted_comfort, 'b-', linewidth=2,
                 label=f'Unconstrained Pareto ({len(unc_pareto_f)})', alpha=0.7)
        plt.scatter(unc_pareto_distances, unc_pareto_comfort, c='blue', s=60,
                    marker='o', edgecolors='darkblue', linewidths=1, alpha=0.8)

    # Plot constrained data (foreground)
    plt.scatter(con_distances, con_comfort, c='lightcoral', alpha=0.6, s=35,
                label=f'Constrained solutions ({len(con_fitness)})')

    # Plot constrained Pareto front (most prominent)
    if len(con_pareto_distances) > 0:
        sorted_indices = np.argsort(con_pareto_distances)
        sorted_dist = np.array(con_pareto_distances)[sorted_indices]
        sorted_comfort = np.array(con_pareto_comfort)[sorted_indices]
        plt.plot(sorted_dist, sorted_comfort, 'r-', linewidth=4,
                 label=f'Constrained Pareto ({len(con_pareto_f)})', alpha=0.9)
        plt.scatter(con_pareto_distances, con_pareto_comfort, c='red', s=100,
                    marker='*', edgecolors='darkred', linewidths=2, zorder=5)

    plt.xlabel('Distance (km)', fontsize=14, fontweight='bold')
    plt.ylabel('Average Comfort Score', fontsize=14, fontweight='bold')
    plt.title('Constrained vs Unconstrained Bicycle Route Optimization\n(Safety≥2.0, Slope≥2.0)',
              fontsize=16, fontweight='bold', pad=20)
    plt.grid(True, alpha=0.3)
    plt.legend(fontsize=12, loc='upper right')

    # Add summary text box
    textstr = f'Unconstrained: {len(unc_pareto_f)} Pareto solutions\n'
    textstr += f'Constrained: {len(con_pareto_f)} Pareto solutions\n'
    if len(unc_distances) > 0 and len(con_distances) > 0:
        textstr += f'Distance range: {min(np.min(unc_distances), np.min(con_distances)):.0f}-{max(np.max(unc_distances), np.max(con_distances)):.0f} km\n'
        textstr += f'Comfort range: {min(np.min(unc_comfort), np.min(con_comfort)):.2f}-{max(np.max(unc_comfort), np.max(con_comfort)):.2f}'

    props = dict(boxstyle='round', facecolor='white', alpha=0.9)
    plt.text(0.02, 0.98, textstr, transform=plt.gca().transAxes, fontsize=11,
             verticalalignment='top', bbox=props)

    plt.tight_layout()
    plt.show()

    # Print comparison statistics
    print(f"\n📊 COMPARISON STATISTICS (DEDUPLICATED)")
    print("=" * 60)
    print(f"{'Metric':<30} {'Unconstrained':<15} {'Constrained':<15}")
    print("-" * 60)
