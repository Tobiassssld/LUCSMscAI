"""---

## 2.3 Generative Adversarial Networks (GANs)

### Our Improvements

1. Generator is based on the improved decoder implementation, with deeper layers and larger
potential dimensions(default 256);
2. The optimizer uses a reduced learning rate for better GAN training;
3. The discriminator freezes parameters when training GAN while dynamically adjust the
generator and discriminator weights to prevent training instability;
4. Adjust the laten dim, filters, and epochs parameters to achieve the best results
"""

def build_gan(data_shape, latent_dim, filters=128, lr=0.0001, beta_1=0.5):
    """
    Constructs the GAN: Generator, Discriminator, and Combined Model
    """
    optimizer = Adam(learning_rate=lr, beta_1=beta_1)

    # Build the generator
    generator = build_deconv_net(latent_dim, activation_out='tanh', filters=filters)

    # Build the discriminator
    discriminator = build_conv_net(data_shape, out_shape=1, filters=filters)
    discriminator.compile(loss='binary_crossentropy', optimizer=optimizer)

    # Freeze discriminator weights when training the GAN
    discriminator.trainable = False
    gan_output = discriminator(generator.output)
    gan = tf.keras.Model(inputs=generator.input, outputs=gan_output)
    gan.compile(loss='binary_crossentropy', optimizer=optimizer)

    return discriminator, generator, gan


def get_batch(generator, dataset, batch_size=64):
    """
    Prepares real and fake batches for discriminator training
    """
    half_batch = batch_size // 2

    # Generate fake images
    latent_vectors = tf.random.normal(shape=(half_batch, latent_dim))
    fake_data = generator(latent_vectors, training=False)

    # Select random real images
    idx = np.random.randint(0, dataset.shape[0], half_batch)
    real_data = dataset[idx]

    # Combine fake and real data
    X = tf.concat([real_data, fake_data], axis=0)
    y = tf.concat([tf.ones((half_batch, 1)), tf.zeros((half_batch, 1))], axis=0)

    return X, y


def train_gan(generator, discriminator, gan, dataset, latent_dim, n_epochs=20, batch_size=64):
    """
    GAN training loop
    """
    batches_per_epoch = dataset.shape[0] // batch_size

    for epoch in range(n_epochs):
        print(f"Epoch {epoch + 1}/{n_epochs}")
        for _ in tqdm(range(batches_per_epoch)):
            # Train the discriminator
            X, y = get_batch(generator, dataset, batch_size)
            discriminator_loss = discriminator.train_on_batch(X, y)

            # Train the generator
            latent_vectors = tf.random.normal(shape=(batch_size, latent_dim))
            y_gan = tf.ones((batch_size, 1))
            generator_loss = gan.train_on_batch(latent_vectors, y_gan)

        # Visualize generated images at the end of each epoch
        noise = tf.random.normal(shape=(16, latent_dim))
        generated_images = generator(noise, training=False).numpy()
        grid_plot(generated_images, name=f"Generated Images (Epoch {epoch + 1})", n=3)

