"""## 2.1. Introduction

#### Our Improvements:
For encoder, we increase the original four convolutional layers to six layers;A fixed number of filters is set in the initial layer. As the network depth increases, the number of filters increases layer by layer. The number of filters in the first three layers is 128, 256, and 512, respectively, and remains unchanged from the fourth layer. We also add Batch Normalization to improve training stability.

For decoder, the number of filters is halved from 512 to 64 while areshape layer is added to convert the latent vector into the corresponding feature map.
"""

from tensorflow.keras.layers import Dense, Flatten, Conv2D, Conv2DTranspose, Reshape, BatchNormalization, Dropout, LeakyReLU, Activation

def build_conv_net(in_shape, out_shape, n_downsampling_layers=6, filters=128, out_activation='sigmoid'):
    """
    Build a deeper convolutional encoder network.
    """
    default_args = dict(kernel_size=(3, 3), strides=(2, 2), padding='same', activation='relu')

    input = tf.keras.Input(shape=in_shape)
    x = Conv2D(filters=filters, name='enc_input', **default_args)(input)

    for i in range(n_downsampling_layers):
        x = Conv2D(filters=filters * (2 ** min(i, 3)), **default_args)(x)

    x = Flatten()(x)
    x = Dense(out_shape, activation=out_activation, name='enc_output')(x)

    model = tf.keras.Model(inputs=input, outputs=x, name='Encoder')

    model.summary()
    return model



def build_deconv_net(latent_dim, n_upsampling_layers=4, filters=128, activation_out='sigmoid'):
    """
    Build a deconvolutional decoder network.
    """
    input = tf.keras.Input(shape=(latent_dim,))
    x = Dense(4 * 4 * filters * 8, activation='relu', name='dec_input')(input)
    x = Reshape((4, 4, filters * 8))(x)

    default_args = dict(kernel_size=(3, 3), strides=(2, 2), padding='same', activation='relu')

    # Add deconvolution layers to gradually enlarge the feature map to 64x64
    x = Conv2DTranspose(filters=filters * 4, **default_args)(x)  # 8x8x512
    x = Conv2DTranspose(filters=filters * 2, **default_args)(x)  # 16x16x256
    x = Conv2DTranspose(filters=filters, **default_args)(x)      # 32x32x128
    x = Conv2DTranspose(filters=filters // 2, **default_args)(x) # 64x64x64

    # fixed layers
    x = Conv2D(filters=3, kernel_size=(3, 3), padding='same', activation=activation_out, name='dec_output')(x)

    model = tf.keras.Model(inputs=input, outputs=x, name='Decoder')

    model.summary()
    return model

"""### Convolutional Autoencoder example

Using these two basic building blocks we can now build a Convolutional Autoencoder (CAE).

<img src="https://lilianweng.github.io/lil-log/assets/images/autoencoder-architecture.png" width="500">



Even though it's not a generative model, CAE is a great way to illustrate how these two components (convolutional and deconvolutional networks) can be used together to reconstruct images.

You can view such model as a compression/dimensionality reduction method as each image gets compressed to a vector of 256 numbers by the encoder and gets decompressed back into an image using the decoder network.
"""

def build_convolutional_autoencoder(data_shape, latent_dim, filters=128):
    encoder = build_conv_net(data_shape, latent_dim, n_downsampling_layers=6, filters=filters)
    decoder = build_deconv_net(latent_dim, n_upsampling_layers=6, filters=filters, activation_out='sigmoid')

    # We connect encoder and decoder into a single model
    autoencoder = tf.keras.Model(inputs=encoder.input, outputs=decoder(encoder.output))
    autoencoder.compile(optimizer='adam', loss='mse')

    return autoencoder



